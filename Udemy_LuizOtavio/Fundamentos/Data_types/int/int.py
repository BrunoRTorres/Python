# Tipos int e float
# int -> Numero inteiro
# O tipo int rpresenta qualquer numero
# positivo ou negativo. int sem sinal e considerado positivo
print(11) # int
print(-11) # int
print(0)


# A funcao type mostra o tipo que o python inferiu ao valor
print(type('Bruno'))
print(type(-1))
print(type(-1.1), type(0.0), type(4.3))
